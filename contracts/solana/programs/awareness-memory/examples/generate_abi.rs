use anchor_lang::{AccountSerialize, InstructionData, ToAccountMetas};
use awareness_memory::{
    accounts, instruction, native_space_id, next_state_root, transition_id, Space,
    TransitionReceipt, ID, VERSION, ZERO,
};
use serde_json::json;
use solana_pubkey::Pubkey;
use std::str::FromStr;

fn hex(bytes: &[u8]) -> String {
    format!(
        "0x{}",
        bytes.iter().map(|b| format!("{b:02x}")).collect::<String>()
    )
}
fn metas(accounts: Vec<solana_instruction::AccountMeta>) -> serde_json::Value {
    json!(accounts
        .iter()
        .map(|a| json!({ "pubkey": a.pubkey.to_string(),
        "isSigner": a.is_signer, "isWritable": a.is_writable }))
        .collect::<Vec<_>>())
}
